// ── CORE FUNCTIONS
function getLang(){ return localStorage.getItem('tl-lang') || 'en'; }

function setLang(lang){
  localStorage.setItem('tl-lang', lang);
  applyLang(lang);
  updateToggles(lang);
  document.documentElement.lang = lang;
}

function applyLang(lang){
  if(lang === 'en') return;
  const t = TL[lang];
  if(!t) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if(!t[key]) return;
    if(el.tagName === 'INPUT') el.placeholder = t[key];
    else if(el.dataset.i18nHtml !== undefined) el.innerHTML = t[key];
    else el.textContent = t[key];
  });
  // html attributes with data-i18n-ph (placeholder)
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.dataset.i18nPh;
    if(t[key]) el.placeholder = t[key];
  });
}

function updateToggles(lang){
  document.querySelectorAll('.tl-lang-btn').forEach(btn => {
    btn.innerHTML = lang === 'es'
      ? '<span class="tl-flag">🇺🇸</span> English'
      : '<span class="tl-flag">🇲🇽</span> Español';
    btn.dataset.target = lang === 'es' ? 'en' : 'es';
    btn.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a Español');
  });
}

// ── BUTTON FACTORY — call this to create a toggle button and insert it
function createLangBtn(insertFn){
  const btn = document.createElement('button');
  btn.className = 'tl-lang-btn';
  const lang = getLang();
  btn.innerHTML = lang === 'es'
    ? '<span class="tl-flag">🇺🇸</span> English'
    : '<span class="tl-flag">🇲🇽</span> Español';
  btn.dataset.target = lang === 'es' ? 'en' : 'es';
  btn.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a Español');
  btn.addEventListener('click', () => setLang(btn.dataset.target));
  insertFn(btn);
  return btn;
}

// ── AUTO INIT
(function init(){
  function run(){
    const lang = getLang();
    if(lang !== 'en') applyLang(lang);
    updateToggles(lang);
    // Wire up any .tl-lang-btn already in the DOM
    document.querySelectorAll('.tl-lang-btn').forEach(btn => {
      btn.addEventListener('click', () => setLang(btn.dataset.target));
    });
  }
  if(document.readyState === 'loading') document.addEventListener('DOMContentLoaded', run);
  else run();
})();
